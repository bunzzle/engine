pub fn public_suffix(domain: &str) -> bool {
    let Some((_, parent)) = domain.split_once('.') else {
        return true;
    };
    let listed = |rule: &str| RULES.contains(&rule);
    if listed(domain) {
        return true;
    }
    listed(&format!("*.{parent}")) && !listed(&format!("!{domain}"))
}

pub fn verifiable(domain: &str) -> bool {
    domain_ok(domain) && !public_suffix(domain)
}
